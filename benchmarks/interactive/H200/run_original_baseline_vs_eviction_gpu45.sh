check_environment() {
  [[ -n "${MODEL}" ]] || fatal "set LIVESERVE_MODEL or MODEL to a local model directory or cached Hugging Face model ID (HF_HUB_OFFLINE defaults to 1)"
  case "${MODEL}" in
    /*|./*|../*) [[ -d "${MODEL}" ]] || fatal "model directory not found: ${MODEL}" ;;
  esac
  liveserve_require_command "${PYBIN}" "python" || exit 2
  # Preserve the selected interpreter when invoking the vllm-omni entry script.
  PYBIN="$(command -v "${PYBIN}")"
  if [[ -z "${VLLM_BIN}" ]]; then
    VLLM_BIN="$(dirname "${PYBIN}")/vllm-omni"
    [[ -x "${VLLM_BIN}" ]] || VLLM_BIN="vllm-omni"
  fi
  liveserve_require_command "${VLLM_BIN}" "vllm-omni (set LIVESERVE_VLLM_BIN or VLLM_BIN)" || exit 2
  VLLM_BIN="$(command -v "${VLLM_BIN}")"
  [[ -f "${VLLM_BIN}" ]] || fatal "vllm-omni must resolve to an executable Python entry script: ${VLLM_BIN}"
  local path variant part
  for path in "${DRIVER}" "${ROOT}/client_bargein.py" "${ROOT}/aggregate_capacity.py" "${ROOT}/aggregate_audio_rtf.py" "${SCHEDULER_POLICY_LIB}" "${REPO_ROOT}/vllm-omni/vllm_omni/benchmarks/audio_continuity.py"; do
    [[ -f "${path}" ]] || fatal "required file not found: ${path}"
  done
  for variant in ${VARIANTS}; do
    path="$(deploy_yaml_for_variant "${variant}")"
    [[ -n "${path}" ]] || fatal "unknown variant '${variant}'"
    [[ -f "${path}" ]] || fatal "deploy yaml not found: ${path}"
  done
  for part in ${TRACE_PARTS}; do
    [[ "${part}" =~ ^[0-9]+$ ]] || fatal "TRACE_PARTS must contain space-separated part numbers; got '${part}'"
    path="${LIVESERVE_TRACE_DIR:-${ROOT}/trace}/total_traces_part${part}.txt"
    [[ -f "${path}" ]] || fatal "trace file not found: ${path}; set LIVESERVE_TRACE_DIR to the trace directory"
  done
}

