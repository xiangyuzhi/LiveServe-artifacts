run_cell() {
  local variant="$1"
  local c="$2"
  local tag="${variant}_c${c}_p0_win${TIME_START}_${TIME_LIMIT}"
  local outdir="${RESULT_ROOT}/${variant}/${tag}"
  local cell_log="${LOGDIR}/${tag}.log"
  local -a prefetch_args=()
  local -a trace_part_args=(--parts ${TRACE_PARTS})
  local -a timeline_args=()
  local -a audio_args=()
  local -a diagnostic_args=()
  while IFS= read -r item; do
    prefetch_args+=("${item}")
  done < <(prefetch_args_for_variant "${variant}")
  if [[ "${RECORD_AUDIO_TIMELINE}" == "1" ]]; then
    timeline_args+=(--record-audio-timeline)
  fi
  if [[ "${WITH_AUDIO}" == "1" ]]; then
    audio_args+=(--with-audio)
  fi
  if [[ "${MAX_REQUESTS}" != "0" ]]; then
    diagnostic_args+=(
      --max-requests "${MAX_REQUESTS}"
      --max-requests-policy "${MAX_REQUESTS_POLICY}"
      --session-balanced-min-turns "${SESSION_BALANCED_MIN_TURNS}"
      --session-balanced-max-turns "${SESSION_BALANCED_MAX_TURNS}"
    )
  fi
  if [[ "${ENFORCE_SESSION_ORDER}" == "1" ]]; then
    diagnostic_args+=(--enforce-session-order)
  fi
  if [[ "${METRICS_START_INDEX}" != "0" ]]; then
    diagnostic_args+=(--metrics-start-index "${METRICS_START_INDEX}")
  fi
  if [[ -n "${METRICS_START_TRACE_TIME}" ]]; then
    diagnostic_args+=(--metrics-start-trace-time "${METRICS_START_TRACE_TIME}")
  fi
  if [[ -n "${METRICS_END_TRACE_TIME}" ]]; then
    diagnostic_args+=(--metrics-end-trace-time "${METRICS_END_TRACE_TIME}")
  fi
  if [[ "${MAX_MEASUREMENT_RESULTS}" != "0" ]]; then
    diagnostic_args+=(--max-measurement-results "${MAX_MEASUREMENT_RESULTS}")
  fi
  if [[ "${MAX_PENDING_REQUEST_TASKS}" != "0" ]]; then
    diagnostic_args+=(--max-pending-request-tasks "${MAX_PENDING_REQUEST_TASKS}")
  fi
  if [[ -n "${AUDIO_START_TRACE_TIME}" ]]; then
    diagnostic_args+=(--audio-start-trace-time "${AUDIO_START_TRACE_TIME}")
  fi
  if [[ -n "${AUDIO_END_TRACE_TIME}" ]]; then
    diagnostic_args+=(--audio-end-trace-time "${AUDIO_END_TRACE_TIME}")
  fi
  if [[ "${FORCE_TRACE_OUTPUT_TOKENS}" == "1" ]]; then
    diagnostic_args+=(--force-trace-output-tokens)
  fi
  if [[ "${WARM_HISTORY_BEFORE_START}" == "1" ]]; then
    diagnostic_args+=(
      --warm-history-before-start
      --warm-history-max-turns-per-user "${WARM_HISTORY_MAX_TURNS_PER_USER}"
    )
  fi
  if [[ "${PREWARM_HISTORY_BEFORE_REPLAY}" == "1" ]]; then
    diagnostic_args+=(
      --prewarm-history-before-replay
      --prewarm-max-users "${PREWARM_MAX_USERS}"
      --prewarm-min-history-tokens "${PREWARM_MIN_HISTORY_TOKENS}"
      --prewarm-max-history-tokens "${PREWARM_MAX_HISTORY_TOKENS}"
      --prewarm-max-inflight "${PREWARM_MAX_INFLIGHT}"
      --prewarm-sort "${PREWARM_SORT}"
    )
    if [[ -n "${PREWARM_TIMEOUT_SEC}" ]]; then
      diagnostic_args+=(--prewarm-timeout-sec "${PREWARM_TIMEOUT_SEC}")
    fi
  fi
  diagnostic_args+=(--history-record-mode "${HISTORY_RECORD_MODE}")
  if [[ -n "${AUDIO_METADATA_PATH}" ]]; then
    diagnostic_args+=(--audio-metadata-path "${AUDIO_METADATA_PATH}")
  fi
  if [[ -f "${outdir}/summary.json" ]]; then
    log "cell ${tag} already complete; skipping"
    return 0
  fi
  if [[ -d "${outdir}" ]]; then
    local aborted_dir="${RESULT_ROOT}/_aborted/${tag}_$(date -u +%Y%m%d_%H%M%S)"
    mkdir -p "${RESULT_ROOT}/_aborted"
    mv "${outdir}" "${aborted_dir}"
    log "archived partial cell ${tag} to ${aborted_dir}"
  fi
  mkdir -p "${outdir}"
  log "starting cell ${tag}"
  local -a driver_cmd=(
    "${PYBIN}" -u "${DRIVER}"
    --url "$(api_url)" \
    --mode smoke \
    "${trace_part_args[@]}" \
    --time-start "${TIME_START}" \
    --time-limit "${TIME_LIMIT}" \
    --speedup "${SPEEDUP}" \
    --max-inflight "${c}" \
    "${audio_args[@]}" \
    --policy fixed_time \
    --interrupt-after-seconds 2.0 \
    --interrupt-jitter-sec 0.5 \
    --interrupt-time-anchor ttfp \
    --interrupt-prob 0 \
    --model "${SERVED_MODEL_NAME}" \
    --progress-interval "${PROGRESS_INTERVAL}" \
    --request-timeout-sec "${REQUEST_TIMEOUT_SEC}" \
    "${timeline_args[@]}" \
    "${diagnostic_args[@]}" \
    "${prefetch_args[@]}" \
    --result-dir "${outdir}"
  )
  local -a driver_cmd_prefix=()
  split_optional_cmd "${DRIVER_NUMACTL_CMD}" driver_cmd_prefix
  if [[ -n "${DRIVER_NUMACTL_CMD}" ]]; then
    log "cell ${tag} driver_numactl='${DRIVER_NUMACTL_CMD}'"
  fi
  if [[ "${CELL_TIMEOUT_SEC}" != "0" ]]; then
    timeout --signal=INT --kill-after=120s "${CELL_TIMEOUT_SEC}" "${driver_cmd_prefix[@]}" "${driver_cmd[@]}" \
      >>"${cell_log}" 2>&1
  else
    "${driver_cmd_prefix[@]}" "${driver_cmd[@]}" >>"${cell_log}" 2>&1
  fi
  local rc=$?
  log "cell ${tag} exit=${rc}"
  if [[ "${rc}" -ne 0 ]]; then
    tail -160 "${cell_log}" | tee -a "${LOGDIR}/run.log" || true
  fi
  return "${rc}"
}

