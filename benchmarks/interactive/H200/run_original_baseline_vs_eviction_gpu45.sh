  for variant in ${VARIANTS}; do
    if ! wait_for_run_quality "${variant}_server_start"; then
      fatal "run quality gate timed out before ${variant}; set RUN_QUALITY_WAIT_BEFORE_VARIANT_SEC=0 to disable waiting"
    fi
    start_server "${variant}" || return $?
    for c in ${CONCURRENCY_LIST}; do
      run_cell "${variant}" "${c}"
      rc=$?
      if [[ "${rc}" -ne 0 && "${rc_total}" -eq 0 ]]; then
        rc_total="${rc}"
      fi
      aggregate_results
    done
    stop_server
    log "cooldown 30s after ${variant}"
    sleep 30
  done
  aggregate_results
  if [[ "${RUN_QUALITY_WAIT_BEFORE_END_SEC}" != "0" ]]; then
    old_wait="${RUN_QUALITY_WAIT_BEFORE_VARIANT_SEC}"
    RUN_QUALITY_WAIT_BEFORE_VARIANT_SEC="${RUN_QUALITY_WAIT_BEFORE_END_SEC}"
    if ! wait_for_run_quality "end_snapshot"; then
      fatal "run quality gate timed out before end snapshot; set RUN_QUALITY_WAIT_BEFORE_END_SEC=0 to disable waiting"
    fi
    RUN_QUALITY_WAIT_BEFORE_VARIANT_SEC="${old_wait}"
  fi
  write_system_snapshot "end"
  nvidia-smi --query-gpu=index,name,memory.used,memory.total,utilization.gpu --format=csv,noheader,nounits >"${RESULT_ROOT}/nvidia_smi_end.txt" || true
  log "DONE rc=${rc_total}; results=${RESULT_ROOT}"
  return "${rc_total}"
