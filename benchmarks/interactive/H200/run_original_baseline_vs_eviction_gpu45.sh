warn_if_high_load() {
  local load1
  load1="$(awk '{print $1}' /proc/loadavg 2>/dev/null || echo 0)"
  "${PYBIN}" - "${load1}" "${RUN_QUALITY_LOAD1_WARN}" "${RUN_QUALITY_ABORT_ON_WARN}" <<'PY'
import sys
load = float(sys.argv[1])
threshold = float(sys.argv[2])
abort_on_warn = sys.argv[3] in {"1", "true", "TRUE", "yes", "YES"}
if load > threshold:
    print(
        f"WARNING: load1={load:.2f} exceeds RUN_QUALITY_LOAD1_WARN={threshold:.2f}; "
        "latency/goodput results may be contaminated"
    )
    if abort_on_warn:
        raise SystemExit(3)
PY
}

warn_if_forbidden_processes() {
  if [[ -z "${RUN_QUALITY_FORBID_PROCESS_RE}" ]]; then
    return 0
  fi
  local matches
  matches="$(
    pgrep -af "${RUN_QUALITY_FORBID_PROCESS_RE}" 2>/dev/null \
      | grep -v 'RUN_QUALITY_FORBID_PROCESS_RE=' \
      | grep -v 'run_original_baseline_vs_eviction_gpu45.sh' \
      | grep -v 'run_original_baseline_vs_eviction_gpu67.sh' \
      | grep -v 'run_eviction_fast_iter_gpu67.sh' \
      | grep -v 'pgrep -af' \
      || true
  )"
  if [[ -z "${matches}" ]]; then
    return 0
  fi
  echo "WARNING: forbidden run-quality process regex matched: ${RUN_QUALITY_FORBID_PROCESS_RE}"
  echo "${matches}" | sed 's/^/  /'
  case "${RUN_QUALITY_ABORT_ON_FORBIDDEN_PROCESS}" in
    1|true|TRUE|yes|YES) return 4 ;;
  esac
  return 0
}

trim_csv_field() {
  local value="$1"
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s' "${value}"
}

collect_descendant_pids() {
  local root_pid="$1"
  local -a queue=("${root_pid}")
  local -a all=("${root_pid}")
  local pid child
  while [[ "${#queue[@]}" -gt 0 ]]; do
    pid="${queue[0]}"
    queue=("${queue[@]:1}")
    while IFS= read -r child; do
      [[ -n "${child}" ]] || continue
      all+=("${child}")
      queue+=("${child}")
    done < <(pgrep -P "${pid}" 2>/dev/null || true)
  done
  printf '%s\n' "${all[@]}"
}

assert_server_gpu_scope() {
  local label="$1"
  [[ "${RUN_QUALITY_ENFORCE_SERVER_GPU_SCOPE}" == "1" ]] || return 0
  [[ -n "${SERVER_PID}" ]] || return 0

  local -A uuid_to_index=()
  local idx uuid rest
  while IFS=',' read -r idx uuid rest; do
    idx="$(trim_csv_field "${idx}")"
    uuid="$(trim_csv_field "${uuid}")"
    [[ -n "${idx}" && -n "${uuid}" ]] || continue
    uuid_to_index["${uuid}"]="${idx}"
  done < <(nvidia-smi --query-gpu=index,uuid --format=csv,noheader,nounits 2>/dev/null || true)

  local pid_set=","
  local pid
  while IFS= read -r pid; do
    [[ -n "${pid}" ]] || continue
    pid_set+="${pid},"
  done < <(collect_descendant_pids "${SERVER_PID}")

  local allowed=",${TEXT_GPUS},"
  local proc mem gpu_idx
  local -a bad=()
  while IFS=',' read -r pid uuid proc mem; do
    pid="$(trim_csv_field "${pid}")"
    uuid="$(trim_csv_field "${uuid}")"
    proc="$(trim_csv_field "${proc}")"
    mem="$(trim_csv_field "${mem}")"
    [[ -n "${pid}" && -n "${uuid}" ]] || continue
    [[ "${pid_set}" == *",${pid},"* ]] || continue
    gpu_idx="${uuid_to_index[${uuid}]:-unknown}"
    if [[ "${allowed}" != *",${gpu_idx},"* ]]; then
      bad+=("pid=${pid} gpu=${gpu_idx} mem=${mem} proc=${proc}")
    fi
  done < <(nvidia-smi --query-compute-apps=pid,gpu_uuid,process_name,used_memory --format=csv,noheader,nounits 2>/dev/null || true)

  if [[ "${#bad[@]}" -gt 0 ]]; then
    log "ERROR: ${label} server descendant compute app(s) outside TEXT_GPUS=${TEXT_GPUS}: ${bad[*]}"
    return 1
  fi
  return 0
}

wait_for_run_quality() {
  local label="$1"
  local max_wait="${RUN_QUALITY_WAIT_BEFORE_VARIANT_SEC}"
  local poll_sec="${RUN_QUALITY_WAIT_POLL_SEC}"
  if [[ "${max_wait}" == "0" ]]; then
    return 0
  fi

  local start_epoch elapsed attempt load1
  start_epoch="$(date +%s)"
  attempt=0
  elapsed=0
  while true; do
    attempt=$((attempt + 1))
    if warn_if_high_load >/dev/null && warn_if_forbidden_processes >/dev/null; then
      if [[ "${attempt}" -gt 1 ]]; then
        log "run quality window ready before ${label} after ${elapsed}s"
      fi
      return 0
    fi
    elapsed=$(( $(date +%s) - start_epoch ))
    load1="$(awk '{print $1}' /proc/loadavg 2>/dev/null || echo unknown)"
    log "waiting before ${label}: elapsed=${elapsed}s load1=${load1} threshold=${RUN_QUALITY_LOAD1_WARN}"
    if [[ "${max_wait}" != "0" && "${elapsed}" -ge "${max_wait}" ]]; then
      return 1
    fi
    sleep "${poll_sec}"
  done
}

